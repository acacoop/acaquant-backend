def _esperadas() -> dict[str, date]:
    out: dict[str, date] = {}
    for linea in _DATOS.strip().splitlines():
        boleto, _, fecha = linea.partition("\t")
        d, m, y = (int(x) for x in fecha.strip().split("/"))
        out[boleto.strip()] = date(y, m, d)
    return out


def main() -> None:
    detalle = "--detalle" in sys.argv
    esperadas = _esperadas()

    with get_pool().connection() as conn, conn.cursor() as cur:
        cur.execute(
            "SELECT boleto, concertacion FROM operaciones.operaciones "
            "WHERE boleto = ANY(%s)", (list(esperadas),))
        en_base = dict(cur.fetchall())

    ok, swap, otra, falta, sin_fecha = [], [], [], [], []
    for boleto, real in esperadas.items():
        if boleto not in en_base:
            falta.append((boleto, real, None))
        elif (base := en_base[boleto]) is None:
            sin_fecha.append((boleto, real, None))
        elif base == real:
            ok.append((boleto, real, base))
        elif base.day == real.month and base.month == real.day:
            swap.append((boleto, real, base))
        else:
            otra.append((boleto, real, base))

    n = len(esperadas)
    print(f"BOLETOS CHEQUEADOS: {n}\n")
    print(f"  ✓ fecha correcta          {len(ok):>4}")
    print(f"  ✗ DIA Y MES DADOS VUELTA  {len(swap):>4}")
    print(f"  ✗ otra diferencia         {len(otra):>4}")
    print(f"  · sin fecha en la base    {len(sin_fecha):>4}")
    print(f"  · no existe en la base    {len(falta):>4}")

    for titulo, grupo in (("DIA Y MES DADOS VUELTA", swap), ("OTRA DIFERENCIA", otra),
                          ("SIN FECHA EN LA BASE", sin_fecha), ("NO EXISTEN", falta)):
        if not grupo:
            continue
        print(f"\n── {titulo} ({len(grupo)}) " + "─" * 30)
        print(f"  {'BOLETO':<18} {'REAL (Excel)':<14} {'EN LA BASE'}")
        for boleto, real, base in (grupo if detalle else grupo[:25]):
            print(f"  {boleto:<18} {real.isoformat():<14} {base.isoformat() if base else '—'}")
        if not detalle and len(grupo) > 25:
            print(f"  … y {len(grupo) - 25} más (corré con --detalle para verlos todos)")

    # Los meses reales que quedaron contaminados: sirve para dimensionar el
    # arreglo sobre el resto del histórico, no solo sobre esta muestra.
    if swap:
        meses = sorted({b.strftime("%Y-%m") for _, _, b in swap})
        print(f"\nMeses donde la base tiene metidos boletos que no son de ahí: {', '.join(meses)}")


if __name__ == "__main__":
    main()
